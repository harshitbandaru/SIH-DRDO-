# Program to demonstrate inbuilt math functions

import math

x = 25
y = 6.7

print("x:", x)
print("y:", y)

# Square root
print("Square root of x:", math.sqrt(x))

# Power
print("x power 3:", math.pow(x, 3))

# Ceil 
print("Ceil of y:", math.ceil(y))

# Floor
print("Floor of y:", math.floor(y))

# Factorial
print("Factorial of 5:", math.factorial(5))

# Trigonometric functions
print("sin(30):", math.sin(math.pi/6))
print("cos(0):", math.cos(0))
print("tan(45):", math.tan(math.pi/4))

# Logarithms
print("Natural log of x:", math.log(x))
print("Log base 10 of x:", math.log10(x))

# Pi and e constants
print("Value of pi:", math.pi)
print("Value of e:", math.e)

