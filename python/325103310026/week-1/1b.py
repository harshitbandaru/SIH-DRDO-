# Demonstrating basic data types in python

# Integer
a = 10
print("Integer:", a, type(a))

# Float
b = 3.14
print("Float:", b, type(b))

# String
c = "Hello World"
print("String:", c, type(c))

# Boolean
d = True
print("Boolean:", d, type(d))

# List
e = [1, 2, 3, 4]
print("List:", e, type(e))

# Tuple
f = (10, 20, 30)
print("Tuple:", f, type(f))

# Set
g = {67, 10, 15}
print("Set:", g, type(g))

# Dictionary
h = {"name": "Yathin", "age": 17}
print("Dictionary:", h, type(h))

# None type
i = None
print("None Type:", i, type(i))

# complex type
j = 3+4j
print("complex:",j,type(j))