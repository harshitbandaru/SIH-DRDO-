# Program to translate mathematical formulas into Python expressions
 
import math

# Area of a Circle
# Formula: A = pi.r^2
r = float(input("Enter radius of circle: "))
area = math.pi * r**2
print("Area of Circle =", area)

# Area of square
# Formula: A = a^2
a = float(input("Enter the side of square: "))
area = a ** 2
print("Area of Square =" , area)