S = [6,3,8,4,7,9]
Y = [2,5]

# Concatenation of two lists
L = S + Y
print(L)

# Concatenation using extend method
S. extend (Y)
print(S)

# Repetition of list
A = S * 2
print(A)

# Slicing
print(S[1:])
print(S[:2])
print(S[:-2])
print(S[-2:])
print(S[::1])
print(S[1:3:2])
# Deleting items from lists
del S[1]
print(S)
